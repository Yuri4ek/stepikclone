"""Базовый пакет учебного содержания Федерации: 3 курса, 9 модулей, 30 шагов.

Перенесено из документа «Кейс хакатона „Образовательная платформа“ · материалы организатора».
Иерархия пакета — курс → модуль → шаг. В модели платформы между модулем и шагом есть урок,
поэтому каждый модуль пакета получает один урок с тем же названием (интерфейс такой урок не показывает).

Соответствие типов шагов пакета и модели:
  Теория               → kind=theory, content.type=theory
  Контрольный вопрос   → kind=quiz,   content.type=quiz (варианты) или answer (число)
  Scratch (ответ)      → kind=quiz,   content.type=scratch_answer
  Scratch (ссылка)     → kind=task,   content.type=scratch
  Minecraft Education  → kind=task,   content.type=minecraft
  Проект               → kind=task,   content.type=project
  Задача с тестами     → kind=code,   content.type=algo

Блоки «Правильный ответ», «Критерии проверки», «Эталонное решение», подсказка и скрытые тесты лежат
в тех же полях content, но ученику не отдаются (app/steps/registry.py: PRIVATE_KEYS, public_code).
Блочные программы записаны в Markdown как ```blocks — фронтенд рисует их блоками.
"""

from __future__ import annotations

from decimal import Decimal
from typing import Any

# Баллы по типам шагов: теория не оценивается, контрольные вопросы — немного, работы — больше
SCORE_QUIZ = Decimal("5")
SCORE_SCRATCH_ANSWER = Decimal("5")
SCORE_SCRATCH_PROJECT = Decimal("10")
SCORE_MINECRAFT = Decimal("15")
SCORE_PROJECT = Decimal("25")
SCORE_ALGO = Decimal("10")


def theory(title: str, markdown: str) -> dict:
    return {"title": title, "kind": "theory", "max_score": Decimal("0"), "content": {"type": "theory", "markdown": markdown.strip()}}


def choice(title: str, question: str, options: list[str], correct: list[int], explanation: str = "") -> dict:
    """Контрольный вопрос с вариантами. correct — номера верных вариантов (с 0)."""
    opts = [{"id": chr(ord("a") + i), "text": t} for i, t in enumerate(options)]
    content: dict[str, Any] = {"type": "quiz", "question": question.strip(), "options": opts}
    if len(correct) == 1:
        content["correct_option_id"] = opts[correct[0]]["id"]
    else:
        content["multiple"] = True
        content["correct_option_ids"] = [opts[i]["id"] for i in correct]
    if explanation:
        content["explanation"] = explanation
    return {"title": title, "kind": "quiz", "max_score": SCORE_QUIZ, "content": content}


def number(title: str, question: str, answer: str, hint: str = "") -> dict:
    content: dict[str, Any] = {"type": "answer", "question": question.strip(), "correct_answer": answer, "answer_kind": "number"}
    if hint:
        content["hint"] = hint
    return {"title": title, "kind": "quiz", "max_score": SCORE_QUIZ, "content": content}


def scratch_answer(title: str, markdown: str, question: str, answer: str, hint: str = "") -> dict:
    content: dict[str, Any] = {
        "type": "scratch_answer",
        "markdown": markdown.strip(),
        "question": question.strip(),
        "correct_answer": answer,
        "answer_kind": "number",
    }
    if hint:
        content["hint"] = hint
    return {"title": title, "kind": "quiz", "max_score": SCORE_SCRATCH_ANSWER, "content": content}


def scratch_project(title: str, markdown: str, criteria: str) -> dict:
    return {
        "title": title,
        "kind": "task",
        "max_score": SCORE_SCRATCH_PROJECT,
        "content": {
            "type": "scratch",
            "markdown": markdown.strip(),
            "criteria": criteria.strip(),
            "submit": {"link": "required", "screenshot": "off", "text": "optional"},
        },
    }


def minecraft(title: str, world: str, markdown: str, criteria: str) -> dict:
    return {
        "title": title,
        "kind": "task",
        "max_score": SCORE_MINECRAFT,
        "content": {
            "type": "minecraft",
            "world": world.strip(),
            "markdown": markdown.strip(),
            "criteria": criteria.strip(),
            "submit": {"link": "required", "screenshot": "required", "text": "optional"},
        },
    }


def project(title: str, markdown: str, criteria: str, submit: dict, link_kind: str) -> dict:
    return {
        "title": title,
        "kind": "task",
        "max_score": SCORE_PROJECT,
        "content": {
            "type": "project",
            "markdown": markdown.strip(),
            "criteria": criteria.strip(),
            "submit": submit,
            "link_kind": link_kind,
        },
    }


def algo(title: str, markdown: str, tests: list[tuple[str, str, bool]], reference: str) -> dict:
    """tests: (ввод, ответ, пример в условии?)"""
    return {
        "title": title,
        "kind": "code",
        "max_score": SCORE_ALGO,
        "content": {
            "type": "algo",
            "markdown": markdown.strip(),
            "language": "python",
            "time_limit_ms": 1000,
            "memory_limit_mb": 256,
            "starter_code": "",
            "tests": [{"input": i, "output": o, "sample": s} for i, o, s in tests],
            "reference_solution": reference.strip() + "\n",
        },
    }


def module(title: str, steps: list[dict]) -> dict:
    return {"title": title, "lessons": [{"title": title, "steps": steps}]}


